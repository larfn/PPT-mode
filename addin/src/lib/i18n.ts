export function normalizeLanguage(value: unknown): UiLanguage {
  return value === 'en' ? 'en' : 'zh';
}

export function getLanguage(): UiLanguage {
  try { return normalizeLanguage(localStorage.getItem(STORAGE_KEY)); } catch { return 'zh'; }
}

export function setLanguage(lang: UiLanguage): void {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignored */ }
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  translateDom(document.body);
}

export function applyLanguageFromConfig(value: unknown): UiLanguage {
  const lang = normalizeLanguage(value ?? getLanguage());
  setLanguage(lang);
  return lang;
}

/** 判定「当前文本是否是外部写入的新内容」：既不是原文也不是原文的英文变体 → 是新内容。 */
export function updatedOriginal(stored: string, current: string): string {
  return current !== stored && current !== translateToEn(stored) ? current : stored;
}

/** 始终把中文原文译成英文（不依赖当前语言），用于识别「原文的英文变体」。 */
export function translateToEn(text: string): string {
  const trimmed = text.trim();
  if (!trimmed) return text;
  // 多行消息（错误弹窗等）逐行翻译
  if (trimmed.includes('\n')) {
    return text.split('\n').map((line) => translateToEn(line)).join('\n');
  }
  const hit = exact[trimmed];
  if (hit) return text.replace(trimmed, hit);
  for (const [re, fn] of patterns) {
    const m = trimmed.match(re);
    if (m) return text.replace(trimmed, fn(m));
  }
  // 结构化兜底：中文括号结构「head（inner）」逐段翻译
  const paren = trimmed.match(/^([^（）]+)（([^（）]*)）$/);
  if (paren) {
    const head = translateToEn(paren[1]);
    const inner = translateToEn(paren[2]);
    if (!/[一-鿿]/.test(head) && !/[一-鿿]/.test(inner)) {
      return text.replace(trimmed, head.trimEnd() + ' (' + inner + ')');
    }
  }
  // 结构化兜底：中文分号连接的并列段逐段翻译
  if (trimmed.includes('；')) {
    const parts = trimmed.split('；');
    if (parts.length > 1) {
      const out = parts.map((p) => translateToEn(p));
      if (out.every((s) => !/[一-鿿]/.test(s))) {
        return text.replace(trimmed, out.join('; '));
      }
    }
  }
  return text;
}

export function translateText(text: string): string {
  if (getLanguage() !== 'en') return text;
  return translateToEn(text);
}

function originalAttr(el: Element, attr: string, value: string): string {
  let map = attrOriginals.get(el);
  if (!map) {
    map = new Map();
    attrOriginals.set(el, map);
  }
  const current = map.get(attr);
  if (current == null) {
    map.set(attr, value);
    return value;
  }
  if (updatedOriginal(current, value) !== current) {
    map.set(attr, value);
    return value;
  }
  return current;
}

function applyTextNode(node: Text): void {
  const current = node.nodeValue || '';
  let original = textOriginals.get(node);
  if (original == null) {
    original = current;
    textOriginals.set(node, original);
  } else if (updatedOriginal(original, current) !== original) {
    // current 既不是原文也不是原文的英文变体 → 外部写入的新内容，更新原文
    original = current;
    textOriginals.set(node, original);
  }
  const next = getLanguage() === 'en' ? translateToEn(original) : original;
  if (node.nodeValue !== next) node.nodeValue = next;
}

function applyAttributes(el: Element): void {
  for (const attr of ['title', 'placeholder', 'aria-label', 'alt', 'data-tip']) {
    const value = el.getAttribute(attr);
    if (value == null) continue;
    const original = originalAttr(el, attr, value);
    const next = getLanguage() === 'en' ? translateText(original) : original;
    if (value !== next) el.setAttribute(attr, next);
  }
}

export function translateDom(root: ParentNode | null = document.body): void {
  if (!root) return;
  if (root instanceof Element) applyAttributes(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (n.nodeType === Node.TEXT_NODE) {
      const p = n.parentElement;
      if (p && ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(p.tagName)) continue;
      applyTextNode(n as Text);
    } else if (n.nodeType === Node.ELEMENT_NODE) {
      applyAttributes(n as Element);
    }
  }
}

export function startAutoTranslate(): void {
  if (observer || typeof MutationObserver === 'undefined') return;
  observer = new MutationObserver((records) => {
    if (getLanguage() !== 'en') return;
    for (const r of records) {
      if (r.type === 'characterData') {
        applyTextNode(r.target as Text);
      } else if (r.type === 'attributes') {
        applyAttributes(r.target as Element);
      } else {
        r.addedNodes.forEach((n) => {
          if (n.nodeType === Node.TEXT_NODE) applyTextNode(n as Text);
          if (n.nodeType === Node.ELEMENT_NODE) translateDom(n as Element);
        });
      }
    }
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['title', 'placeholder', 'aria-label', 'alt', 'data-tip']
  });
}
